import React, { useState } from 'react';
import { Card, Badge, Tooltip, OverlayTrigger, Collapse, Button } from 'react-bootstrap';
import { FaRobot, FaInfoCircle, FaChevronDown, FaChevronUp, FaUserShield } from 'react-icons/fa';
import { motion } from 'framer-motion';

/**
 * AiInsight Component
 * 
 * Displays AI-generated content with ethical transparency features.
 * 
 * Props:
 * - title: Heading for the insight
 * - content: The AI generated text
 * - confidence: 'high' | 'medium' | 'low'
 * - sources: Array of strings (data sources used)
 * - type: 'explanation' | 'advice' | 'summary' | 'alert'
 */
const AiInsight = ({ title, content, confidence = 'medium', sources = [], type = 'explanation' }) => {
    const [showSources, setShowSources] = useState(false);

    const getConfidenceConfig = (level) => {
        switch (level?.toLowerCase()) {
            case 'high':
                return { color: 'success', icon: 'High Confidence', variant: 'success' };
            case 'medium':
                return { color: 'warning', icon: 'Medium Confidence', variant: 'warning' };
            case 'low':
                return { color: 'danger', icon: 'Low Confidence (Review Needed)', variant: 'danger' };
            default:
                return { color: 'secondary', icon: 'Unknown Confidence', variant: 'secondary' };
        }
    };

    const confConfig = getConfidenceConfig(confidence);

    const renderTooltip = (props) => (
        <Tooltip id="ai-transparency-tooltip" {...props} className="custom-tooltip">
            <strong>Why am I seeing this?</strong><br />
            This content was generated by AI using your recent academic data (Login logs, LMS grades, Attendance).
            Always verify important decisions.
        </Tooltip>
    );

    return (
        <motion.div
            initial={{ opacity: 0, y: 10 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ duration: 0.4 }}
        >
            <Card className="ai-panel border-0 mb-4">
                <Card.Body className="p-4">
                    <div className="d-flex align-items-center justify-content-between mb-3">
                        <div className="d-flex align-items-center gap-2">
                            <div className="bg-light rounded-circle p-2 d-flex align-items-center justify-content-center" style={{ width: '40px', height: '40px' }}>
                                <FaRobot className="text-primary ai-icon-glow" size={20} />
                            </div>
                            <h6 className="mb-0 fw-bold text-primary">{title}</h6>
                        </div>

                        <div className="d-flex align-items-center gap-2">
                            <Badge
                                bg={confConfig.variant}
                                className={`bg-opacity-10 text-${confConfig.variant} border border-${confConfig.variant} border-opacity-25`}
                            >
                                <FaUserShield className="me-1" /> {confConfig.icon}
                            </Badge>

                            <OverlayTrigger
                                placement="top"
                                delay={{ show: 250, hide: 400 }}
                                overlay={renderTooltip}
                            >
                                <span className="text-muted" style={{ cursor: 'help' }}>
                                    <FaInfoCircle size={16} />
                                </span>
                            </OverlayTrigger>
                        </div>
                    </div>

                    <div className="ai-text mb-3">
                        {content}
                    </div>

                    <div className="d-flex align-items-center justify-content-between pt-3 border-top border-light">
                        <small className="text-muted fst-italic">
                            Generated by EWS-AI Engine
                        </small>

                        {sources.length > 0 && (
                            <Button
                                variant="link"
                                size="sm"
                                className="text-decoration-none text-muted d-flex align-items-center gap-1 p-0"
                                onClick={() => setShowSources(!showSources)}
                            >
                                {showSources ? 'Hide Sources' : 'View Data Sources'}
                                {showSources ? <FaChevronUp size={12} /> : <FaChevronDown size={12} />}
                            </Button>
                        )}
                    </div>

                    <Collapse in={showSources}>
                        <div className="mt-2 text-muted small bg-light p-3 rounded">
                            <strong className="d-block mb-2">Data used for this insight:</strong>
                            <ul className="mb-0 ps-3">
                                {sources.map((source, idx) => (
                                    <li key={idx}>{source}</li>
                                ))}
                            </ul>
                        </div>
                    </Collapse>
                </Card.Body>
            </Card>
        </motion.div>
    );
};

export default AiInsight;
